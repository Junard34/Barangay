-- FIX: public.evidence_files for the LIVE schema
-- Run in: Supabase Dashboard -> SQL Editor
-- ============================================
-- The live database uses SERIAL/INTEGER ids (supabase-migration.sql),
-- but evidence_files was created with UUID complaint_id/uploaded_by and no
-- file_size column, so it cannot reference complaints/users and uploads
-- cannot be saved. The table is currently empty, so it is safe to recreate.

DROP TABLE IF EXISTS public.evidence_files CASCADE;

CREATE TABLE public.evidence_files (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  complaint_id INTEGER NOT NULL REFERENCES public.complaints(id) ON DELETE CASCADE,
  uploaded_by INTEGER REFERENCES public.users(id) ON DELETE CASCADE,
  file_name   TEXT NOT NULL,
  file_url    TEXT NOT NULL,
  file_type   TEXT,
  file_size   BIGINT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_evidence_files_complaint_id ON public.evidence_files (complaint_id);
CREATE INDEX idx_evidence_files_uploaded_by  ON public.evidence_files (uploaded_by);

ALTER TABLE public.evidence_files ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Service role full access" ON public.evidence_files
  FOR ALL USING (true) WITH CHECK (true);
